function validateEVAInterface(EVA)
% VALIDATEEVAINTERFACE Check the saved physiology-to-hardware contract.
% Inputs: EVA.
% Outputs: None.
% Units: SI; degC and explicit _min/_hr/_g field suffixes where used.
% Side effects: None; returns results through its output arguments.
assert(isstruct(EVA) && all(isfield(EVA, {'Inputs','Nominal','OffNominal'})), ...
    'EVA:RunSimulationFirst', 'Run Metabolic_EVA_Sim.m before PLSS_Thermal_Sizing.m.');
Cases = ["Nominal", "OffNominal"];
for Index = 1:numel(Cases)
    Scenario = EVA.(Cases(Index));
    assert(all(isfield(Scenario, {'Case','Metabolic','Physiology','SizingProfile'})), ...
        'EVA:ScenarioFields', 'Incomplete %s scenario.', Cases(Index));
    assert(string(Scenario.Case) == replace(Cases(Index), 'OffNominal', 'Off-nominal'), ...
        'EVA:ScenarioLabel', 'Scenario label does not match its data group.');
    Rates = Scenario.Metabolic;
    assert(all(ismember({'MetabolicRate_W','ExternalWork_W','HeatGeneration_W'},Rates.Properties.VariableNames)), ...
        'EVA:HeatInputFields','Rerun Metabolic_EVA_Sim.m to create corrected Qgen histories.');
    assert(all(Rates.ExternalWork_W>=0) && all(Rates.HeatGeneration_W>0) ...
        && max(abs(Rates.MetabolicRate_W-Rates.ExternalWork_W-Rates.HeatGeneration_W))<1e-8, ...
        'EVA:HeatInputBalance','Heat generation must equal M minus external work exactly once.');
    Rebuilt = Data_Functions.Data.buildSizingProfile(EVA, Cases(Index));
    ExpectedTransfer = Data_Functions.Data.buildThermalInterface(EVA,Cases(Index));
    assert(isfield(Scenario,'ThermalInterface') && isequaln(ExpectedTransfer,Scenario.ThermalInterface), ...
        'EVA:ThermalTransferInterface','Rerun Metabolic_EVA_Sim.m to export current physical thermal pathways.');
    P = Scenario.Physiology;
    Stored = cumsum(P.BodyStorage_W.*(P.EndTime_min-P.StartTime_min)*60) ...
        /(1000*EVA.Inputs.Body.Weight_kg);
    assert(max(abs(Stored-P.BodyStoredHeat_kJ_kg)) < 1e-8, ...
        'EVA:StoredHeatInterface','Stored heat does not match the physical energy balance.');
    assert(isequal(logical(P.HeatStorageBelowZero),Stored < -1e-9), ...
        'EVA:ColdStorageInterface','Below-zero flags must match physical integrated heat.');
    Control = EVA.Inputs.Environment.LCG.Controller;
    if Control.Enabled
        assert(all(P.LCGInletTemperature_C >= Control.TemperatureBounds_C(1)-1e-9 ...
            & P.LCGInletTemperature_C <= P.LCGInletUpperBound_C+1e-9), ...
            'EVA:LCGTemperatureInterface','Controlled LCG inlet is outside configured bounds.');
    end
    MinimumFlow_kg_s = EVA.Inputs.Environment.LCG.MassFlow_kg_s;
    MaximumFlow_kg_s = MinimumFlow_kg_s;
    if Control.Enabled && EVA.Inputs.Environment.LCG.Enabled
        ExpectedUpper = Control.TemperatureBounds_C(2);
        assert(max(abs(P.LCGInletUpperBound_C-ExpectedUpper)) < 1e-8, ...
            'EVA:LCGFixedUpperBound','Upper inlet bound must equal the configured fixed limit.');
    end
    if Control.Enabled && Control.FlowControlEnabled && EVA.Inputs.Environment.LCG.Enabled
        MaximumFlow_kg_s = Control.MaximumFlow_kg_h/3600;
    end
    assert(all(P.LCGMassFlow_kg_s >= MinimumFlow_kg_s-1e-12 ...
        & P.LCGMassFlow_kg_s <= MaximumFlow_kg_s+1e-12), ...
        'EVA:LCGFlowInterface','Controlled LCG flow is outside configured bounds.');
    if Control.Enabled && Control.FlowControlEnabled && EVA.Inputs.Environment.LCG.Enabled
        Release_kg_h = -diff(P.LCGMassFlow_kg_s)*3600;
        AllowedRelease_kg_h = Control.FlowReleaseRate_kg_h_min ...
            *(P.EndTime_min(2:end)-P.StartTime_min(2:end));
        assert(all(Release_kg_h <= AllowedRelease_kg_h+1e-8), ...
            'EVA:LCGFlowRelease','Accepted flow decreases exceed the configured release rate.');
    end
    HeatResidual_W = P.MetabolicHeat_W-P.LCGCooling_W ...
        -P.Convection_W-P.Radiation_W-P.SkinEvaporation_W ...
        -P.RespiratorySensible_W-P.RespiratoryLatent_W-P.BodyStorage_W;
    assert(max(abs(HeatResidual_W)) < 1e-5,'EVA:BodyHeatBalance', ...
        'Physical body heat balance must close.');
    assert(isequal(logical(P.HeatStorageLimitExceeded), ...
        Stored > Control.LimitStoredHeat_kJ_kg+1e-9), ...
        'EVA:HeatLimitInterface','Heat-storage flags differ from the physical history.');
    assert(isequaln(Rebuilt, Scenario.SizingProfile), ...
        'EVA:StaleProfile', 'Sizing profile differs from its saved physiological history.');
end
assert(isfield(EVA.Inputs,'MetabolicFOS') && isfield(EVA,'Sizing') ...
    && all(isfield(EVA.Sizing,{'Nominal','OffNominal'})), ...
    'EVA:MissingDesignLoads','Rerun Metabolic_EVA_Sim.m to create post-simulation FOS loads.');
for Index = 1:numel(Cases)
    Expected = Data_Functions.Data.buildFactoredSizingCase(EVA,Cases(Index));
    assert(isequaln(Expected,EVA.Sizing.(Cases(Index))), ...
        'EVA:StaleDesignLoads','Factored sizing loads differ from the physical results and configured FOS.');
end
end
