function Profile = buildSizingProfile(EVA, CaseName)
% BUILDSIZINGPROFILE Construct a validated interval-level thermal sizing input.
% Inputs: EVA, CaseName.
% Outputs: Profile.
% Units: SI; degC and explicit _min/_hr/_g field suffixes where used.
% Side effects: None; returns results through its output arguments.
assert(any(string(CaseName) == ["Nominal","OffNominal"]), ...
    'EVA:ScenarioName', 'Use Nominal or OffNominal.');
P = EVA.(CaseName).Physiology;
Environment = EVA.Inputs.Environment;
Required = {'StartTime_min','EndTime_min','VaporToPLSS_g_min', ...
    'NeckAirTemperature_C','TorsoAirTemperature_C','LegAirTemperature_C', ...
    'NeckOutlet_C','TorsoOutlet_C','LegOutlet_C','NeckOutletW','TorsoOutletW','LegOutletW', ...
    'LCGInletTemperature_C','LCGInletUpperBound_C','LCGOutletTemperature_C','BodyStoredHeat_kJ_kg','LCGMassFlow_kg_s','RemainingCoolingShortfall_W','HeatStorageBelowZero'};
assert(istable(P) && all(ismember(Required, P.Properties.VariableNames)) && height(P) > 0, ...
    'EVA:ProfileFields', 'Rerun Metabolic_EVA_Sim.m to create the controlled physiological history.');
assert(all(isfinite(P{:,Required}), 'all'), 'EVA:ProfileValues', 'Nonfinite physiological history.');
dt = P.EndTime_min-P.StartTime_min;
assert(all(dt > 0) && all(abs(P.StartTime_min(2:end)-P.EndTime_min(1:end-1)) < 1e-8), ...
    'EVA:ProfileTime', 'Time intervals must be positive, contiguous, and in minutes.');
SupplyPv_Pa = exp(16.6536-4030.183/(Environment.AirTemperature_C+235)) ...
    * Environment.RelativeHumidity_percent/100*1000;
Pressure_Pa = Environment.Pressure_kPa*1000;
DryFlow_kg_s = (Pressure_Pa-SupplyPv_Pa) ...
    * Environment.Ventilation.Flow_CFM*0.028316846592/60 ...
    / (259.84*(Environment.AirTemperature_C+273.15));
assert(DryFlow_kg_s > 0, 'EVA:DryGasFlow', 'Supply must contain positive dry-gas flow.');
SupplyW = (0.01801528/0.0319988)*SupplyPv_Pa/(Pressure_Pa-SupplyPv_Pa);
N = height(P);
Profile = table(P.StartTime_min, P.EndTime_min, P.VaporToPLSS_g_min, P.VaporToPLSS_g_min, ...
    repmat(Environment.Pressure_kPa,N,1), repmat(DryFlow_kg_s,N,1), ...
    repmat(Environment.AirTemperature_C,N,1), repmat(SupplyW,N,1), ...
    P.NeckAirTemperature_C, P.TorsoAirTemperature_C, P.LegAirTemperature_C, ...
    P.NeckOutlet_C, P.TorsoOutlet_C, P.LegOutlet_C, P.NeckOutletW, P.TorsoOutletW, P.LegOutletW, ...
    'VariableNames', {'StartTime_min','EndTime_min','DesignMoisture_g_min','PhysicalMoisture_g_min', ...
    'Pressure_kPa','DryOxygenFlow_kg_s','SupplyTemperature_C','SupplyHumidityRatio', ...
    'NeckMean_C','TorsoMean_C','LegMean_C','NeckOutlet_C','TorsoOutlet_C','LegOutlet_C', ...
    'NeckOutletW','TorsoOutletW','LegOutletW'});
Profile = [Profile, P(:,{'LCGInletTemperature_C','LCGInletUpperBound_C','LCGOutletTemperature_C','BodyStoredHeat_kJ_kg','LCGMassFlow_kg_s','RemainingCoolingShortfall_W','HeatStorageBelowZero'})];
OutletW = P{:,{'NeckOutletW','TorsoOutletW','LegOutletW'}};
MeanW = ([repmat(SupplyW,N,1),OutletW(:,1:2)]+OutletW)/2;
Profile = [Profile, array2table(MeanW, 'VariableNames', {'NeckMeanW','TorsoMeanW','LegMeanW'})];
assert(max(abs(DryFlow_kg_s*(OutletW(:,3)-SupplyW)-P.VaporToPLSS_g_min/60000)) < 2e-8, ...
    'EVA:MoistureInterface', 'Regional outlets and total moisture flow are inconsistent.');
end
