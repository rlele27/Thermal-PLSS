function Transfer = buildThermalInterface(EVA,CaseName)
% BUILDTHERMALINTERFACE Export physical body loads and alternative gas boundaries.
% Inputs: completed EVA and case name. Outputs: interval tables in SI units.
% Side effects: None. Positive heat leaves the body; no sizing FOS applied.
P = EVA.(CaseName).Physiology;
S = EVA.(CaseName).SizingProfile;
E = EVA.Inputs.Environment;
N = height(P);
AirSensible_W = P.Convection_W + P.RespiratorySensible_W;
AirLatent_W = P.SkinEvaporation_W + P.RespiratoryLatent_W;
Residual_W = P.MetabolicHeat_W-P.LCGCooling_W-P.Radiation_W ...
    -AirSensible_W-AirLatent_W-P.BodyStorage_W;
assert(max(abs(Residual_W)) < 1e-5,'EVA:ThermalTransferBalance', ...
    'Exported body heat pathways must close before sizing margins.');
Transfer.BodyPathways = table(P.StartTime_min,P.EndTime_min,P.MetabolicHeat_W, ...
    P.LCGCooling_W,P.Radiation_W,AirSensible_W,AirLatent_W, ...
    P.BodyStorage_W,Residual_W, ...
    'VariableNames',{'StartTime_min','EndTime_min','Qgen_W','LCGHeatPickup_W', ...
    'HeatToSuitInterior_W','HeatToVentilationSensible_W','HeatToVentilationLatent_W', ...
    'BodyStorage_W','ClosureResidual_W'});
% Alternative ventilation interface: use these states instead of adding body
% sensible/latent sources again. Local condensation/storage alters return vapor.
Transfer.Ventilation = table(P.StartTime_min,P.EndTime_min,S.DryOxygenFlow_kg_s, ...
    S.Pressure_kPa,S.SupplyTemperature_C,S.SupplyHumidityRatio, ...
    P.CondenserInletTemperature_C,P.LegOutletW,P.CondenserInletRH_percent, ...
    P.VaporToSuit_g_min,P.VaporToPLSS_g_min,P.CondensateStart_g,P.CondensateEnd_g, ...
    'VariableNames',{'StartTime_min','EndTime_min','DryOxygenFlow_kg_s', ...
    'Pressure_kPa','SupplyTemperature_C','SupplyHumidityRatio', ...
    'ReturnTemperature_C','ReturnHumidityRatio','ReturnRH_percent', ...
    'BodyVaporSource_g_min','VaporDeliveredToPLSS_g_min','CondensateStart_g','CondensateEnd_g'});
% Preserve segment-specific radiant boundary values if supplied (N by 17).
Radiant_C = repmat(reshape(E.RadiantTemperature_C,1,[]),N,1);
if ismember('LinerStartTemperature_C',P.Properties.VariableNames)
    Radiant_C = P.LinerStartTemperature_C;
    Transfer.Liner = P(:,{'StartTime_min','EndTime_min','LinerStartTemperature_C', ...
        'LinerEndTemperature_C','LinerReferenceTemperature_C','Radiation_W', ...
        'LinerStorage_W','LinerOnwardHeat_W','LinerStoredEnergy_kJ'});
end
Transfer.BoundaryConditions = table(P.StartTime_min,P.EndTime_min,Radiant_C, ...
    P.LCGInletTemperature_C,P.LCGOutletTemperature_C,P.LCGMassFlow_kg_s, ...
    'VariableNames',{'StartTime_min','EndTime_min','AssumedInnerRadiantTemperature_C', ...
    'LCGInletTemperature_C','LCGOutletTemperature_C','LCGMassFlow_kg_s'});
end
