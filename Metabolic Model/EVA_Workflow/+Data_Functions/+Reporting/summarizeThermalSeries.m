function Summary = summarizeThermalSeries(Quantity,Unit,Basis,Values,Duration_min,CaseName)
% SUMMARIZETHERMALSERIES Min/time-weighted average/max for thermal sizing.
% Inputs: column labels, common basis, N-by-K histories, N interval durations, case.
% Output: wide nominal/off-nominal table. Unavailable case columns are NaN.
% Units: supplied explicitly per quantity. No side effects or load factoring.
Duration_min = Duration_min(:);
assert(size(Values,1)==numel(Duration_min) && size(Values,2)==numel(Quantity) ...
    && numel(Unit)==numel(Quantity),'EVA:ThermalSummaryShape','Thermal summary dimensions do not match.');
assert(all(isfinite(Values),'all') && all(isfinite(Duration_min)) ...
    && all(Duration_min>=0) && sum(Duration_min)>0, ...
    'EVA:ThermalSummaryValues','Thermal histories must be finite with positive total duration.');
K = numel(Quantity); Missing = nan(K,1);
Summary = table(string(Quantity(:)),string(Unit(:)),repmat(string(Basis),K,1), ...
    Missing,Missing,Missing,Missing,Missing,Missing, ...
    'VariableNames',{'Quantity','Unit','Basis','NominalMinimum','NominalAverage', ...
    'NominalMaximum','OffNominalMinimum','OffNominalAverage','OffNominalMaximum'});
assert(any(string(CaseName)==["Nominal","OffNominal"]),'EVA:ThermalSummaryCase','Unknown case.');
Columns = string(CaseName)+["Minimum","Average","Maximum"];
Summary{:,Columns} = [min(Values,[],1)', ...
    (sum(Values.*Duration_min,1)/sum(Duration_min))',max(Values,[],1)'];
% Moisture inventories/rates and humidity belong in their dedicated reports.
% Retain latent/phase-change heat duties and coolant water temperatures/flows.
MoistureRow = ismember(Summary.Unit,["g","g/min","kg/kg dry oxygen"]) ...
    | ~cellfun('isempty',regexpi(cellstr(Summary.Quantity), ...
    'humidity|moisture|water removal|retained liquid|stored water capacity|gaswaterresidual|RH(?:_|\b)'));
Summary(MoistureRow,:) = [];

end
